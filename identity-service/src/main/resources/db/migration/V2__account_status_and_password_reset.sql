alter table users add column status varchar(255) default 'ACTIVE' not null;
alter table users add constraint ck_users_status check (status in ('ACTIVE', 'SUSPENDED'));

-- A reset token is stored only as a SHA-256 hash, so a database leak cannot be used to reset passwords.
-- Using a token deletes it, which makes it single-use.
create table password_reset_tokens (
    id bigint generated by default as identity primary key,
    user_id bigint not null,
    token_hash varchar(64) not null,
    expires_at timestamp(6) with time zone not null,
    created_at timestamp(6) with time zone not null,
    constraint uk_password_reset_tokens_hash unique (token_hash),
    constraint fk_password_reset_tokens_user foreign key (user_id) references users (id) on delete cascade
);

create index idx_password_reset_tokens_user_id on password_reset_tokens (user_id);
